/**
 * تبدیل کد result به پیام خوانا (برای لاگ و پیام خطا).
 */
export function describeTaraResult(result: unknown): string {
  let code = '';

  if (typeof result === 'string') {
    code = result.trim();
  } else if (typeof result === 'number') {
    code = String(result);
  }

  const message = TARA_RESULT_MESSAGES[code];

  return message ? `result=${code} (${message})` : `result=${code || 'نامشخص'}`;
}

