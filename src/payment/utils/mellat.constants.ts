/** تبدیل مقدار بازگشتی توابع ملت به کد پاسخ تمیز (رشتهٔ رقم‌ها) */
export function normalizeMellatResCode(value: unknown): string {
  if (typeof value === 'number' && Number.isFinite(value)) {
    return String(value);
  }

  if (typeof value !== 'string') {
    return '';
  }

  return value.trim();
}

/**
 * مقدار بازگشتی bpPayRequest یک رشتهٔ دو بخشی است: «ResCode,RefId»
 * (نمونهٔ مستند: `0, AF82041a2Bf6989c7fF9`)
 *
 * RefId به کاراکتر حساس است و باید دقیقاً همان چیزی باشد که بانک داده،
 * پس فاصله‌های اطراف هر دو بخش گرفته می‌شود.
 */
export function parseMellatPayResponse(raw: unknown): {
  resCode: string;
  refId: string;
} {
  let text = '';

  if (typeof raw === 'string') {
    text = raw;
  } else if (typeof raw === 'number' && Number.isFinite(raw)) {
    text = String(raw);
  }

  const commaIndex = text.indexOf(',');

  if (commaIndex === -1) {
    return { resCode: text.trim(), refId: '' };
  }

  return {
    resCode: text.slice(0, commaIndex).trim(),
    refId: text.slice(commaIndex + 1).trim(),
  };
}

/** شرح فارسی کد پاسخ (مطابق جدول شماره ۱۱ مستند) */
export function describeMellatResCode(resCode: unknown): string {
  const code = normalizeMellatResCode(resCode);
  const message = MELLAT_RESPONSE_CODES[code];

  return message
    ? `کد ${code} (${message})`
    : `کد ${code || 'نامشخص'} (بدون شرح در مستند)`;
}

/** آیا این کد یعنی «وضعیت تراکنش هنوز روشن نیست»؟ */
export function isMellatInconclusive(resCode: unknown): boolean {
  return MELLAT_INCONCLUSIVE_CODES.has(normalizeMellatResCode(resCode));
}

/** نتیجهٔ تأیید خرید: کد ۰ و ۴۳ هر دو موفق محسوب می‌شوند */
export function isMellatVerifyAccepted(resCode: unknown): boolean {
  const code = normalizeMellatResCode(resCode);

  return code === MELLAT_SUCCESS || code === MELLAT_ALREADY_VERIFIED;
}

/** نتیجهٔ واریز وجه: کد ۰ و ۴۵ هر دو موفق محسوب می‌شوند */
export function isMellatSettleAccepted(resCode: unknown): boolean {
  const code = normalizeMellatResCode(resCode);

  return code === MELLAT_SUCCESS || code === MELLAT_ALREADY_SETTLED;
}
