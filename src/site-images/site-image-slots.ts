/**
 * کلیدهای مجاز جایگاه‌های تصویر صفحه اصلی.
 *
 * هر جایگاه یک کلید یکتا دارد که هم در دیتابیس (جدول `site_images`) و هم در
 * فرانت‌اند به‌عنوان شناسه‌ی همان تصویر استفاده می‌شود. کلیدها عمداً ثابت‌اند
 * و مدیر نمی‌تواند کلید جدید بسازد؛ چون فرانت‌اند فقط همین جایگاه‌های
 * شناخته‌شده را رندر می‌کند و کلید ناشناخته هیچ‌جا نمایش داده نمی‌شود.
 *
 * تصویر دسکتاپ همیشه لازم است؛ تصویر موبایل اختیاری است و اگر آپلود نشود،
 * همان تصویر دسکتاپ روی موبایل هم نمایش داده می‌شود.
 *
 * نام نمایشی، اندازه‌ی پیشنهادی و تصویر پیش‌فرض هر جایگاه در فرانت‌اند
 * (`front/lib/home-images.ts`) نگهداری می‌شود؛ چون همان‌جاست که رندر
 * می‌شود. این‌جا فقط اعتبارسنجی کلید انجام می‌شود.
 */
export const SITE_IMAGE_SLOT_KEYS = [
  /** پوستر ویدیوی اول هدر صفحه اصلی */
  'home.hero-1-poster',
  /** پوستر ویدیوی دوم هدر صفحه اصلی */
  'home.hero-2-poster',
  /** بنر فروش ویژه، زیر هدر صفحه اصلی */
  'home.sale-banner',
  /** تصویر بزرگ بخش دسته‌بندی‌ها (دسکتاپ) */
  'home.category-1',
  /** تصویر مربعی بخش دسته‌بندی‌ها */
  'home.category-2',
  /** پوستر ویدیوی پایانی صفحه اصلی */
  'home.end-video-poster',
] as const;

export type SiteImageSlotKey = (typeof SITE_IMAGE_SLOT_KEYS)[number];

/** آیا این کلید یک جایگاه شناخته‌شده است؟ */
export function isKnownSiteImageSlot(key: string): boolean {
  return (SITE_IMAGE_SLOT_KEYS as readonly string[]).includes(key);
}
